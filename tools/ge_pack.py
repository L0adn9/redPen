#!/usr/bin/env python3
"""Build the Gemini Enterprise kit from the same files the prototype runs (so nothing drifts).

    python3 tools/ge_pack.py            # writes agents/gemini-enterprise/PASTE-SHEET.md and dist/drive/RedPen/...

PASTE-SHEET.md: every workflow step in canvas order with its settings, the exact instructions to paste,
the pass-through addendum (only if day-1 check #13 fails) and the output JSON schema.
dist/drive/RedPen/: the folder tree to upload to Google Drive (assessments, policy, example verdicts).
"""
import json
import pathlib
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import redpen_audit as ra  # noqa: E402
import redpen_insight  # noqa: E402

OUT = ROOT / "agents" / "gemini-enterprise" / "PASTE-SHEET.md"
DRIVE = ROOT / "dist" / "drive" / "RedPen"

AUDIT_STEPS = [
    ("01-intake", "Intake", "01-intake.md", "Flash",
     "Trigger input `Assessment folder path` (manual) or the new Drive file (event). Connected app: **Google Drive**, "
     "restricted to `/RedPen/Assessments/`.", None),
    ("02-copy_paster", "AI student 1: Copy-paster", "02-persona-copy-paster.md", "Flash (Pro in the \"Pro students\" copy)",
     "Output of **Intake**. No connected apps (it must not see anything else).", "02-persona"),
    ("02-prompt_engineer", "AI student 2: Prompt engineer", "03-persona-prompt-engineer.md",
     "Flash (Pro in the \"Pro students\" copy)", "Output of **Intake**. No connected apps.", "02-persona"),
    ("02-honest_helper", "AI student 3: Honest helper", "04-persona-honest-helper.md",
     "Flash (Pro in the \"Pro students\" copy)", "Output of **Intake**. No connected apps.", "02-persona"),
    ("05-examiner", "Examiner", "05-examiner.md", "**Flash in both copies** (calibration: Flash 7/7, Pro 5/7)",
     "Outputs of **Intake** + all three AI students. No connected apps.", None),
    ("06-verdict", "Verdict", "06-verdict.md", "Flash",
     "Outputs of **Intake** + **Examiner** (+ the run date variable if the builder offers one). Then a **Drive: create "
     "file** action saving the output to `/RedPen/Verdicts/<file_name>`.", None),
]


def block(text, lang=""):
    return f"```{lang}\n{text.strip()}\n```\n"


def build_sheet():
    rules = ra.passthrough_rules()
    git = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    out = [f"""# Gemini Enterprise paste sheet (generated)

Generated by `python3 tools/ge_pack.py` from the files the prototype runs (commit `{git or 'local'}`). **Do not edit by hand**:
change `agents/**/*.md` or `agents/schemas/`, then regenerate. Each block here is byte-for-byte what `tools/redpen_audit.py`
sends to Gemini, and `python3 tools/test_engine.py` must pass before you paste.

## Before you start
1. App setup, Drive data store and folders: `agents/audit/00-build-guide.md` §0. Upload `dist/drive/RedPen/` (made by this script).
2. **Day-1 check #13 decides the mode.** Build Intake + Copy-paster, then ask the Copy-paster step to also repeat the module code
   from Intake. If later steps can read *any* earlier step's output, use **direct mode** (ignore the pass-through blocks).
   If a step only sees the step right before it, add each step's **pass-through addendum** at the end of its instructions,
   and run the personas one after another (the prototype has tested this: `python3 tools/redpen_audit.py <folder> --mode passthrough`).
3. For every Gemini Agent step: **Output format = JSON**. If the step offers an output schema, paste the schema below.
4. After each test run, check the result: `python3 tools/ge_compare.py <MODULE> <ASSESSMENT>` and paste the Verdict JSON.

---

# Workflow 1: RedPen Audit
Triggers: **Manual** (input `Assessment folder path`), **Event: Google Drive** (new file in `/RedPen/Assessments/`),
**Schedule** (monthly, 1st Monday 09:00, Asia/Kuala_Lumpur).
"""]
    for i, (step, title, md, model, inputs, schema_key) in enumerate(AUDIT_STEPS, 1):
        sk = schema_key or step
        schema = (ra.SCHEMAS / f"{sk}.schema.json").read_text(encoding="utf-8")
        instr = ra.instructions(md)
        if step == "06-verdict":
            instr = instr.replace('model: "pro"', 'model: "flash"').replace('"model": "pro"', '"model": "flash"')
        out.append(f"\n## Step {i}: {title}\n")
        out.append(f"| Setting | Value |\n|---|---|\n| Step type | Gemini Agent |\n| Model | {model} |\n"
                   f"| Input | {inputs} |\n| Output format | JSON (schema below) |\n| Source | `agents/audit/{md}` |\n\n")
        out.append("**Instructions (paste):**\n\n" + block(instr))
        if step in rules:
            out.append("\n**Pass-through addendum** (only if check #13 fails; paste at the end of the instructions):\n\n"
                       + block(rules[step]))
        out.append("\n<details><summary>Output schema</summary>\n\n" + block(schema, "json") + "\n</details>\n")
        if step == "06-verdict":
            out.append("\nThen add **Drive: create file**: folder `/RedPen/Verdicts/`, name = the verdict's `file_name`, "
                       "content = the step output. If the Drive trigger for the Fix workflow fails, also add **Gmail: send** "
                       "with subject `RedPen verdict <MODULE> <ASSESSMENT>` (fallback in `agents/verdict-format.md`).\n")

    fix = ROOT / "agents" / "fix"
    out.append(f"""
---

# Workflow 2: RedPen Fix (Hassan)
Trigger: **Event: Google Drive**, new file in `/RedPen/Verdicts/`. Steps: Condition (exposure HIGH or MEDIUM) → Redesign →
**Approval** (added by hand) → Jira create/update → Drive create file → Gmail send → Calendar create event (HIGH only).
Full settings: `agents/fix/00-build-guide.md` and `agents/fix/02-condition-approval-actions.md`.

## Redesign step
| Setting | Value |
|---|---|
| Step type | Gemini Agent |
| Model | Flash |
| Input | The verdict file + Drive (`/RedPen/Assessments/` for the brief, `/RedPen/Policy/`) |
| Output format | JSON (schema below) |

**Instructions (paste):**

{block(ra.re.search(r"^## Instructions.*?^```[a-z]*\n(.*?)^```", (fix / "01-redesign.md").read_text(), ra.re.S | ra.re.M).group(1))}
<details><summary>Output schema</summary>

{block((ra.SCHEMAS / "07-redesign.schema.json").read_text(), "json")}
</details>

---

# Chat agent: RedPen Insight
Type: **Agent** (chat). Data stores: **Jira Cloud** (project RP) + **Google Drive** (`/RedPen/`). Model: Flash.
Test questions: the 4 in `agents/audit/07-insight-chat-agent.md` (the prototype answers all 4: `python3 tools/redpen_insight.py "..."`).

**Instructions (paste):**

{block(redpen_insight.instructions())}
""")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(out), encoding="utf-8")
    return OUT


def build_drive():
    if DRIVE.exists():
        shutil.rmtree(DRIVE)
    n = 0
    for base in ("data/sample-assessments", "data/pilot-real"):
        for folder in sorted((ROOT / base).glob("*/*")):
            if not (folder / "brief.txt").exists():
                continue
            dest = DRIVE / "Assessments" / folder.parent.name / folder.name
            dest.mkdir(parents=True, exist_ok=True)
            for f in ("rubric.txt", "clo-map.txt", "brief.txt"):  # upload order: brief.txt LAST (it fires the trigger)
                shutil.copy(folder / f, dest / f)
            n += 1
    for sub in ("Verdicts", "Revised", "Calibration"):
        (DRIVE / sub).mkdir(parents=True, exist_ok=True)
    pol = DRIVE / "Policy"
    pol.mkdir(parents=True, exist_ok=True)
    for f in (ROOT / "data" / "policy").glob("*"):
        shutil.copy(f, pol / f.name)
    ex = DRIVE / "Verdicts" / "_examples"
    ex.mkdir(parents=True, exist_ok=True)
    for f in (ROOT / "data" / "fake-verdicts").glob("*.json"):
        shutil.copy(f, ex / f.name)
    (DRIVE / "README.txt").write_text(
        "Upload this RedPen folder to Google Drive (My Drive or a shared drive).\n"
        "In each Assessments/<MODULE>/<ASSESSMENT>/ folder, upload rubric.txt and clo-map.txt first and brief.txt last:\n"
        "the Drive event trigger fires on the new file, and the folder must be complete when it does.\n"
        "Verdicts/_examples holds two example verdicts for building the Fix workflow before real ones exist.\n")
    return n


if __name__ == "__main__":
    p = build_sheet()
    n = build_drive()
    print(f"wrote {p.relative_to(ROOT)} ({p.stat().st_size // 1024} KB)")
    print(f"wrote {DRIVE.relative_to(ROOT)}/ ({n} assessments + Policy, Verdicts, Revised, Calibration)")
